"""Agent 5 — Dubbing / TTS (see docs/agent-pipeline.md).

Input: context.dialogue_lines (translated_text, already passed safety check),
       context.characters (to get voice_profile_metadata)
Output: each dialogue_line gets a dubbed_audio_gcs_uri

Only dubs lines with safety_status == "ok" — "flagged" lines wait for a human
reviewer to fix first (see AGENTS.md principle #5, docs/agent-pipeline.md Agent 4).
"""

import uuid

from worker.models.pipeline_context import PipelineContext
from worker.services.gemini_client import GeminiClient
from worker.services.storage import StorageClient

_DEFAULT_VOICE_STYLE = "neutral, clear"
# style_description is supposed to be just 2-4 keywords (see VOICE_SELECTION_PROMPT),
# but it's free text generated by Gemini itself — we can't be 100% sure it
# always complies even though the prompt constrains it clearly.
# DUBBING_AUDIO_INSTRUCTION stuffs style_description directly into the TTS
# instruction ("Speak in a {style} voice: {text}"); a long sentence here
# reproduces exactly the real bug "the redubbed audio also contains the
# instruction sentence" that we got real feedback on — blocking it here acts
# as a last line of defense, not relying solely on the prompt.
#
# Markers are in ENGLISH (not Vietnamese) because VOICE_SELECTION_PROMPT's
# negative example verbs ("NO verbs like 'chose'/'because'/'fits'") were
# translated to English — style_description is now anchored to come back in
# English too, so a leaked full sentence would use these English verbs, not
# the Vietnamese ones this safety net used to check for.
_MAX_VOICE_STYLE_CHARS = 40
_VOICE_STYLE_SENTENCE_MARKERS = (".", " because ", " chose ", " fits ")


class DubbingAgent:
    def __init__(self, gemini: GeminiClient, gcs: StorageClient):
        self._gemini = gemini
        self._gcs = gcs

    def _character_for(self, context: PipelineContext, character_id: str | None):
        if character_id is None:
            return None
        return next((c for c in context.characters if c.id == character_id), None)

    def _voice_style_for(self, context: PipelineContext, character_id: str | None) -> str:
        character = self._character_for(context, character_id)
        if character is None:
            return _DEFAULT_VOICE_STYLE
        style = character.voice_profile_metadata.get("style_description", _DEFAULT_VOICE_STYLE)
        if len(style) > _MAX_VOICE_STYLE_CHARS or any(
            marker in style for marker in _VOICE_STYLE_SENTENCE_MARKERS
        ):
            return _DEFAULT_VOICE_STYLE
        return style

    def _voice_name_for(self, context: PipelineContext, character_id: str | None) -> str | None:
        """Prebuilt voice (one of 12 fixed voices) chosen by Agent 2 by
        listening to a real audio sample (see voice_profiling_agent.py +
        gemini_client.py:select_voice_for_speaker) — ONLY used when the
        character has no voice_id (Voice Design, see _voice_id_for) — if
        None, synthesize_dubbed_audio falls back to hash(character_id) like
        the old version (e.g. a character created before these features
        existed)."""
        character = self._character_for(context, character_id)
        if character is None:
            return None
        return character.voice_profile_metadata.get("voice_name")

    def _voice_id_for(self, context: PipelineContext, character_id: str | None) -> str | None:
        """Custom synthesized voice via Voice Design (see
        voice_profiling_agent.py::build_voice_profile_metadata +
        gemini_client.py::design_voice) — matches the original voice's
        characteristics far better than the 12 prebuilt voices from
        _voice_name_for, PREFERRED when available (see
        synthesize_dubbed_audio: voice_id is checked before voice_name)."""
        character = self._character_for(context, character_id)
        if character is None:
            return None
        return character.voice_profile_metadata.get("voice_id")

    async def run(self, context: PipelineContext) -> PipelineContext:
        for line in context.dialogue_lines:
            if line.safety_status != "ok" or not line.translated_text:
                continue  # skip flagged lines or lines not yet translated — waiting for review
            if line.dubbed_audio_gcs_uri:
                # already dubbed in a previous run (mid-pipeline resume),
                # avoid re-spending Gemini cost
                continue

            audio_bytes = await self._gemini.synthesize_dubbed_audio(
                dialogue_line_id=line.id,
                text=line.translated_text,
                target_lang=context.target_language,
                # voice_style is COMPLETELY IGNORED by
                # gemini_client.synthesize_dubbed_audio when the character has
                # a voice_id (Voice Design) — see the comment there. It's
                # still computed and passed unconditionally here (no
                # branching on voice_id) so we don't have to duplicate the
                # "does the character have a voice_id" logic in two places;
                # do NOT "clean this up" by stuffing real content into
                # style_description for the voice_id branch — that's exactly
                # the bug that caused the audio to read the instruction
                # sentence out loud (see voice_profiling_agent.py).
                voice_style=self._voice_style_for(context, line.character_id),
                character_id=line.character_id,
                voice_name=self._voice_name_for(context, line.character_id),
                voice_id=self._voice_id_for(context, line.character_id),
            )
            # uuid4 in the filename (do NOT reuse the exact same old path on
            # every dub) — real bug encountered: redubbing a line wrote the
            # new audio to the EXACT same old path
            # (jobs/{job_id}/dubbed/{line_id}.wav); the browser had already
            # cached the response for that URL from before (e.g. before a
            # prompt bug was fixed) and kept serving the OLD audio even though
            # the backend had correctly overwritten the new audio on GCS/
            # local storage, and even after a Cache-Control: no-store header
            # was added — the new header could NOT un-poison a browser cache
            # entry that was already cached BEFORE that header existed.
            # Changing the path on every dub (the same way a GCS signed URL
            # always has its own expiring query param that self-busts the
            # cache) completely removes any chance of hitting a stale cache,
            # regardless of whether the browser honors the header or not.
            blob_name = f"jobs/{context.job_id}/dubbed/{line.id}-{uuid.uuid4().hex[:8]}.wav"
            line.dubbed_audio_gcs_uri = await self._gcs.upload_bytes(
                audio_bytes, blob_name, content_type="audio/wav"
            )

        context.current_stage = "dubbed"
        return context
